<?php
declare(strict_types=1);
require __DIR__ . '/../vendor/autoload.php';
use Magebean\Engine\Checks\DependencyPolicyCheck;
use Magebean\Engine\Context;
$root = sys_get_temp_dir() . '/magebean-dependency-policy-' . bin2hex(random_bytes(8)); mkdir($root);
$check = new DependencyPolicyCheck(new Context($root, ''));
$count = 0;
$assert = static function(bool $ok, string $message) use (&$count): void { $count++; if (!$ok) throw new RuntimeException($message); };
$write = static function(string $name, array $data) use ($root): void { file_put_contents($root . '/' . $name, json_encode($data)); };
$args = ['policy_file' => 'policy.json'];
$package = ['name' => 'private/module', 'version' => '1.0.0', 'source' => ['url' => 'ssh://private.example/module', 'reference' => 'abc123'], 'replace' => ['vendor/original' => '1.0.0']];
$policy = ['schema_version' => 1, 'root_repositories' => [['type' => 'vcs', 'url' => 'ssh://private.example/module']], 'packages' => ['private/module' => ['source' => $package['source'], 'replace' => $package['replace']]]];
try {
    $assert($check->sourcePolicy($args)[0] === null, 'Missing data is unresolved');
    $write('composer.json', ['repositories' => $policy['root_repositories']]); $write('composer.lock', ['packages' => [$package], 'packages-dev' => []]); $write('policy.json', $policy);
    $assert($check->sourcePolicy($args)[0] === true, 'Explicit private namespace/source/revision policy passes');
    $assert($check->sourcePolicy(['policy_file' => $root . '/policy.json'])[0] === null, 'Absolute policy path is rejected');
    $assert($check->sourcePolicy(['policy_file' => '../' . basename($root) . '/policy.json'])[0] === null, 'Traversal path is rejected even when resolving inside project');
    $write('composer.lock', ['packages' => []]);
    $assert($check->sourcePolicy($args)[0] === null, 'Empty Magento dependency inventory cannot pass');
    file_put_contents($root . '/composer.lock', '{"packages":[');
    $assert($check->sourcePolicy($args)[0] === null, 'Truncated JSON cannot pass');
    $write('composer.lock', ['packages' => [$package]]);
    $outside = tempnam(sys_get_temp_dir(), 'magebean-outside-'); file_put_contents($outside, json_encode($policy));
    if (symlink($outside, $root . '/outside-policy.json')) {
        $assert($check->sourcePolicy(['policy_file' => 'outside-policy.json'])[0] === null, 'Outside-project symlink is rejected');
        unlink($root . '/outside-policy.json');
    }
    unlink($outside);
    $changed = $package; $changed['source']['reference'] = 'other'; $write('composer.lock', ['packages' => [$changed]]);
    $assert($check->sourcePolicy($args)[0] === false, 'Revision mismatch fails');
    $write('composer.lock', ['packages' => [$package, ['name' => 'other/pkg', 'version' => '2.0.0']]]);
    $assert($check->sourcePolicy($args)[0] === null, 'Unknown package cannot be excluded');
    $write('composer.lock', ['packages' => [$changed, ['name' => 'other/pkg', 'version' => '2.0.0']]]);
    $assert($check->sourcePolicy($args)[0] === false, 'Known violation survives partial coverage');
    $write('composer.lock', ['packages' => [$package]]); $write('composer.json', ['repositories' => [['type' => 'path', 'url' => '../module']]]);
    $assert($check->sourcePolicy($args)[0] === false, 'Root source override is checked');
    $write('composer.json', ['repositories' => $policy['root_repositories']]); $changed = $package; unset($changed['source']); $write('composer.lock', ['packages' => [$changed]]);
    $assert($check->sourcePolicy($args)[0] !== true, 'Missing repository identity cannot pass');
    $changed = $package; unset($changed['replace']); $write('composer.lock', ['packages' => [$changed]]);
    $assert($check->sourcePolicy($args)[0] === false, 'Replacement policy mismatch fails');
    $archive = ['name' => 'private/archive', 'version' => '2', 'dist' => ['url' => 'https://packages.example/archive.zip', 'reference' => 'release2']];
    $policy['packages'] = ['private/archive' => ['dist' => $archive['dist']]]; $write('policy.json', $policy); $write('composer.lock', ['packages' => [$archive]]);
    $assert($check->sourcePolicy($args)[0] === true, 'Non-Git dist identity explicitly covered');
    $archive['dist']['reference'] = ''; $write('composer.lock', ['packages' => [$archive]]);
    $assert($check->sourcePolicy($args)[0] === null, 'Unversioned dist cannot pass');
    $record = ['id' => 'temporary-1', 'advisory' => 'CVE-example', 'package' => 'private/module', 'version' => '1', 'owner' => 'operations', 'action' => 'documented action', 'rollback' => 'documented rollback', 'expires_at' => gmdate('Y-m-d\TH:i:s\Z', time() + 86400)];
    $inventory = ['schema_version' => 1, 'generated_at' => gmdate('Y-m-d\TH:i:s\Z'), 'records' => [$record]];
    $margs = ['inventory_file' => 'mitigations.json', 'expected_ids' => ['temporary-1']];
    $write('mitigations.json', $inventory);
    $assert($check->mitigationRecords($margs)[0] === true, 'Complete declared record structure passes only schema criterion');
    $assert($check->mitigationRecords(['inventory_file' => 'mitigations.json', 'expected_ids' => []])[0] === null, 'Empty expected coverage policy cannot pass');
    $assert($check->mitigationRecords(['inventory_file' => 'mitigations.json'])[0] === null, 'No explicit expected coverage policy cannot pass');
    $inventory['records'][0]['expires_at'] = '2000-01-01T00:00:00Z'; $write('mitigations.json', $inventory);
    $assert($check->mitigationRecords($margs)[0] === false, 'Expired record fails');
    $inventory['generated_at'] = '2000-01-01T00:00:00Z'; $write('mitigations.json', $inventory);
    $assert($check->mitigationRecords($margs)[0] === null, 'Stale inventory cannot pass');
    $inventory['generated_at'] = '2099-01-01T00:00:00Z'; $write('mitigations.json', $inventory);
    $assert($check->mitigationRecords($margs)[0] === null, 'Future inventory cannot pass');
    $inventory['generated_at'] = gmdate('Y-m-d\TH:i:s\Z'); $inventory['records'] = []; $write('mitigations.json', $inventory);
    $assert($check->mitigationRecords($margs)[0] === false, 'Expected record omission fails');
    $inventory['records'] = [$record, $record]; $write('mitigations.json', $inventory);
    $assert($check->mitigationRecords($margs)[0] === false, 'Duplicate identity fails');
    $inventory['records'] = [$record]; unset($inventory['records'][0]['rollback']); $write('mitigations.json', $inventory);
    $assert($check->mitigationRecords($margs)[0] === false, 'Incomplete lifecycle field fails');
    $inventory['generated_at'] = '2026-02-30T00:00:00Z'; $write('mitigations.json', $inventory);
    $assert($check->mitigationRecords($margs)[0] === null, 'Invalid calendar timestamp unresolved');
    file_put_contents($root . '/mitigations.json', 'mitigation rollback');
    $assert($check->mitigationRecords($margs)[0] === null, 'Keywords are not structured evidence');
    echo "Dependency policy: $count assertions passed\n";
} finally { foreach (glob($root . '/*') ?: [] as $path) unlink($path); rmdir($root); }
